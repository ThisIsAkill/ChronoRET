#!/usr/bin/env python3
"""
verify.py — Prove every byte the source emits is byte-exact, independent of
the base ROM, and count matched bytes per bank.

`make diff` assembles over a copy of the original ROM, so a region the source
never writes still "matches". This tool closes that gap: it assembles the same
source onto two synthetic bases (all $00 and all $FF). A byte is *emitted by
source* exactly when both builds agree on it; every such byte must equal the
real ROM.

The data layer (asm/data/, generated by tools/extract_data.py; asm/rom.asm
is asm/main.asm and the data layer) is checked apart and never counts as
emitted by source here: the whole ROM is assembled isolated as well, with
every file the manifest (symbols/data_assets.csv) lists as an incbin, and
only those, present as placeholders of a third value, so the bytes they
place are told apart from the bytes the source writes; and asm/data/ is
assembled on its own too (code labels as label-only stubs), and may write
no byte outside the manifest's pieces. Its figures: bytes
written by source as fill or as pointer tables of labels, bytes extracted
from the ROM, and bytes packed by the build from extracted assets; every
ROM byte must be one of these or emitted by the code source. Text pieces
(tools/text.py) are encoded by the build from text extracted from the ROM:
counted apart as well, never as source.

Usage:
    python3 tools/verify.py                 verify, print per-bank totals
    python3 tools/verify.py --json          same, machine-readable
    python3 tools/verify.py --ranges        also list emitted ranges

Exit status is non-zero on any mismatch or assembler error.
"""

import argparse
import json
import re
import sys
import tempfile
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import c3pack  # noqa: E402
import extract_data  # noqa: E402
import isolated  # noqa: E402

ROM_PATH = Path('roms/chrono_trigger.sfc')
MAIN_ASM = Path('asm/main.asm')
ROM_ASM = Path('asm/rom.asm')
ROM_SIZE = 0x400000


def assemble_onto(fill: int, workdir: Path, root: Path = Path('.')) -> bytes:
    """The source assembled onto an image of `fill`, where it cannot read the
    ROM (tools/isolated.py: a copy of asm/ only, no roms/ or build/, every
    file asar opens checked). The packed $C3 module's incbin gets a
    placeholder of the fill byte, so its bytes are not "emitted by source"
    here; main() checks them on their own."""
    c3pack.ensure_built(root)           # the packed $C3 module, checked against the ROM in main()
    iso = Path(workdir) / f'isolated_{fill:02x}'
    iso.mkdir()
    try:
        tree = isolated.make_tree(root, iso)
    except isolated.IsolationError as e:
        sys.stderr.write(f'verify: {e}\n')
        sys.exit(2)
    placeholder = tree / c3pack.MODULE_LZ
    placeholder.parent.mkdir(parents=True)
    placeholder.write_bytes(bytes([fill]) * c3pack.MODULE_PACKED_SIZE)
    out = iso / f'base_{fill:02x}.sfc'
    out.write_bytes(bytes([fill]) * ROM_SIZE)
    try:
        isolated.run_asar(['--no-title-check', '--fix-checksum=off', str(MAIN_ASM), str(out.resolve())],
                          tree, iso)
    except isolated.IsolationError as e:
        sys.stderr.write(f'verify: {e}\n')
        sys.exit(2)
    return out.read_bytes()


def assemble_whole(base: int, placeholder: int, workdir: Path, root: Path = Path('.')) -> bytes:
    """asm/rom.asm (the code source and the data layer) assembled isolated
    onto an image of `base`, every incbin the manifest lists (and the
    packed module) a placeholder of `placeholder`. Nothing else is in the
    tree: an incbin of any other file fails, and strace refuses a read from
    outside it."""
    iso = Path(workdir) / f'whole_{base:02x}'
    iso.mkdir()
    try:
        tree = isolated.make_tree(root, iso)
        files = extract_data.placeholder_files(extract_data.read_manifest())
        files[c3pack.MODULE_LZ] = c3pack.MODULE_PACKED_SIZE
        for rel, size in files.items():
            (tree / rel).parent.mkdir(parents=True, exist_ok=True)
            (tree / rel).write_bytes(bytes([placeholder]) * size)
        out = iso / 'whole.sfc'
        out.write_bytes(bytes([base]) * ROM_SIZE)
        isolated.run_asar(['--no-title-check', '--fix-checksum=off', str(ROM_ASM), str(out.resolve())],
                          tree, iso)
    except (isolated.IsolationError, extract_data.DataError) as e:
        sys.stderr.write(f'verify: {e}\n')
        sys.exit(2)
    return out.read_bytes()


DATA_ONLY = Path('asm/data_only.asm')     # written into the isolated tree only


def code_label_stubs(workdir: Path, root: Path = Path('.')) -> str:
    """Label-only stubs (`org` and a label, no bytes) for the global labels
    of the code source at banks $C0-$FF, from an isolated assembly of
    asm/main.asm with asar's symbol output: what the data layer may
    reference when it is assembled without the code."""
    iso = Path(workdir) / 'labels'
    iso.mkdir()
    try:
        tree = isolated.make_tree(root, iso)
        ph = tree / c3pack.MODULE_LZ
        ph.parent.mkdir(parents=True, exist_ok=True)
        ph.write_bytes(bytes(c3pack.MODULE_PACKED_SIZE))
        out, sym = iso / 'code.sfc', iso / 'code.sym'
        out.write_bytes(bytes(ROM_SIZE))
        isolated.run_asar(['--no-title-check', '--fix-checksum=off', '--symbols=wla',
                           f'--symbols-path={sym.resolve()}', str(MAIN_ASM), str(out.resolve())], tree, iso)
        text = sym.read_text()
    except isolated.IsolationError as e:
        sys.stderr.write(f'verify: {e}\n')
        sys.exit(2)
    stubs, section = ['hirom'], None
    for line in text.splitlines():
        if line.startswith('['):
            section = line.strip()
            continue
        m = re.match(r'^([0-9A-Fa-f]{2}):([0-9A-Fa-f]{4}) ([A-Za-z_][A-Za-z0-9_]*)$', line)
        if section == '[labels]' and m and int(m.group(1), 16) >= 0xC0:
            stubs.append(f'org ${m.group(1)}{m.group(2)}\n{m.group(3)}:')
    return '\n'.join(stubs) + '\n'


def assemble_data_only(base: int, placeholder: int, workdir: Path, stubs: str,
                       root: Path = Path('.')) -> bytes:
    """asm/data/data.asm assembled isolated without the code source (its
    references to code labels resolved by label-only stubs), onto an image
    of `base`, the manifest's files placeholders of `placeholder`."""
    iso = Path(workdir) / f'data_{base:02x}'
    iso.mkdir()
    try:
        tree = isolated.make_tree(root, iso)
        for rel, size in extract_data.placeholder_files(extract_data.read_manifest()).items():
            (tree / rel).parent.mkdir(parents=True, exist_ok=True)
            (tree / rel).write_bytes(bytes([placeholder]) * size)
        (tree / DATA_ONLY).write_text(stubs + 'incsrc "data/data.asm"\n')
        out = iso / 'data.sfc'
        out.write_bytes(bytes([base]) * ROM_SIZE)
        isolated.run_asar(['--no-title-check', '--fix-checksum=off', str(DATA_ONLY), str(out.resolve())],
                          tree, iso)
    except (isolated.IsolationError, extract_data.DataError) as e:
        sys.stderr.write(f'verify: {e}\n')
        sys.exit(2)
    return out.read_bytes()


def data_writes_outside(workdir: Path, root: Path = Path('.')) -> list[int]:
    """Offsets the data layer, assembled on its own, writes outside the
    manifest's pieces (a write over a code byte is caught here even when it
    keeps the byte's value, which the whole-ROM comparison cannot see)."""
    stubs = code_label_stubs(workdir, root)
    a = assemble_data_only(0x00, 0xFF, workdir, stubs, root)
    b = assemble_data_only(0xFF, 0x00, workdir, stubs, root)
    inside = bytearray(ROM_SIZE)
    for p in extract_data.read_manifest():
        inside[p['offset']:p['stop']] = b'\x01' * (p['stop'] - p['offset'])
    return [i for i in range(ROM_SIZE) if not inside[i] and not (a[i] == 0x00 and b[i] == 0xFF)]


def check_data_layer(rom: bytes, lo: bytes, hi: bytes, emitted: set[int]) -> tuple[dict, list[str]]:
    """The data layer's figures and problems (see the docstring). `lo`/`hi`
    are the code source's isolated assemblies, `emitted` its bytes."""
    import build_rom
    pieces = extract_data.read_manifest()
    with tempfile.TemporaryDirectory() as tmp:
        a = assemble_whole(0x00, 0xFF, Path(tmp))
        b = assemble_whole(0xFF, 0x00, Path(tmp))
        outside = data_writes_outside(Path(tmp))
    problems = []
    if outside:
        problems.append(f'asm/data/ writes {len(outside):,} byte(s) outside the manifest\'s pieces, '
                        f'the first at {extract_data.addr(outside[0])}')
    kind = bytearray(ROM_SIZE)          # 0 unwritten, 1 source, 2 placeholder
    for i in range(ROM_SIZE):
        if a[i] == b[i]:
            kind[i] = 1
        elif a[i] == 0xFF and b[i] == 0x00:
            kind[i] = 2
    unwritten = kind.count(0)
    if unwritten:
        first = kind.index(0)
        problems.append(f'{unwritten:,} byte(s) of asm/rom.asm are written by nothing, the first at '
                        f'{extract_data.addr(first)}')
    want = bytearray(ROM_SIZE)          # 1 code or source data, 2 an incbin of the manifest or the module
    for i in emitted:
        want[i] = 1
    figures = {'fill_bytes': 0, 'table_bytes': 0, 'extracted_bytes': 0, 'packed_bytes': 0, 'text_bytes': 0}
    for p in pieces:
        s, e = p['offset'], p['stop']
        if any(want[s:e]):
            problems.append(f'{p["label"]} ({p["start"]}-{p["end"]}) overlaps bytes the code source emits')
        source = p['piece'] in ('fill', 'table')
        want[s:e] = bytes([1 if source else 2]) * (e - s)
        figures[p['piece'] + '_bytes'] += e - s
    m0 = c3pack.MODULE_ROM
    want[m0:m0 + c3pack.MODULE_PACKED_SIZE] = bytes([2]) * c3pack.MODULE_PACKED_SIZE
    if kind != want:
        diff = [i for i in range(ROM_SIZE) if kind[i] != want[i]]
        problems.append(f'{len(diff):,} byte(s) of asm/rom.asm are not placed as the manifest says '
                        f'(source or incbin), the first at {extract_data.addr(diff[0])}')
    if any(a[i] != lo[i] for i in emitted):
        problems.append('the data layer changes bytes the code source emits')
    bad = [i for i in range(ROM_SIZE) if kind[i] == 1 and a[i] != rom[i]]
    if bad:
        problems.append(f'{len(bad):,} byte(s) the source writes differ from the ROM, the first at '
                        f'{extract_data.addr(bad[0])}')
    # The real assets and packs: what the build incbins must be the ROM's bytes.
    try:
        extract_data.extract()
        build_rom.build_packs()
        build_rom.build_text()
    except (extract_data.DataError, build_rom.BuildError) as e:
        problems.append(str(e))
        return figures, problems
    for p in pieces:
        if p['piece'] not in ('extracted', 'packed', 'text'):
            continue
        path = (extract_data.ASSETS / p['asset'] if p['piece'] == 'extracted'
                else extract_data.PACKS / f'{p["label"]}.lz' if p['piece'] == 'packed'
                else extract_data.TEXT_OUT / f'{p["label"]}.bin')
        if path.read_bytes() != rom[p['offset']:p['stop']]:
            problems.append(f'{path} is not the ROM\'s bytes at {p["start"]}-{p["end"]}')
    return figures, problems


def to_ranges(offsets: list[int]) -> list[tuple[int, int]]:
    ranges = []
    for off in offsets:
        if ranges and ranges[-1][1] == off:
            ranges[-1] = (ranges[-1][0], off + 1)
        else:
            ranges.append((off, off + 1))
    return ranges


def bank_name(offset: int) -> str:
    # HiROM: file bank N is SNES bank $C0+N ($00-$3F:8000-FFFF are mirrors).
    return f'${0xC0 + (offset >> 16):02X}'


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    ap.add_argument('--json', action='store_true')
    ap.add_argument('--ranges', action='store_true')
    args = ap.parse_args()

    if not ROM_PATH.exists():
        sys.stderr.write(f'No ROM at {ROM_PATH}\n')
        return 2
    rom = ROM_PATH.read_bytes()
    if len(rom) != ROM_SIZE:
        sys.stderr.write(f'Expected unheadered {ROM_SIZE}-byte ROM\n')
        return 2

    with tempfile.TemporaryDirectory() as tmp:
        lo = assemble_onto(0x00, Path(tmp))
        hi = assemble_onto(0xFF, Path(tmp))

    emitted = [i for i in range(ROM_SIZE) if lo[i] == hi[i]]
    mismatched = [i for i in emitted if lo[i] != rom[i]]

    # The packed $C3 module: bankC3.asm incbins what tools/c3pack.py packs
    # from the module's source (a placeholder in the isolated assemblies), so
    # it is checked here on its own: the packed bytes must be the ROM's. How
    # much of the unpacked module is source comes from c3pack.source_bytes(),
    # isolated the same way.
    packed = range(c3pack.MODULE_ROM, c3pack.MODULE_ROM + c3pack.MODULE_PACKED_SIZE)
    built = c3pack.MODULE_LZ.read_bytes()
    packed_emitted = len(built)
    mismatched += [c3pack.MODULE_ROM + k for k in range(len(packed))
                   if k >= len(built) or built[k] != rom[c3pack.MODULE_ROM + k]]
    data, data_problems = check_data_layer(rom, lo, hi, set(emitted) - set(packed))
    per_bank: dict[str, int] = {}
    for i in emitted:
        if i in packed:
            continue
        name = bank_name(i)
        per_bank[name] = per_bank.get(name, 0) + 1

    if args.json:
        print(json.dumps({
            'emitted_bytes': len(emitted),
            'mismatched_bytes': len(mismatched),
            'per_bank': per_bank,
            'packed_module_bytes': packed_emitted,
            'data_layer': data,
            'file_check': isolated.run_mode(),
            'ranges': [[s, e] for s, e in to_ranges(emitted)] if args.ranges else None,
        }, indent=2))
    else:
        for name in sorted(per_bank):
            print(f'  {name:<16} {per_bank[name]:>7,} bytes emitted by source')
        if packed_emitted:
            try:
                source = len(c3pack.source_bytes())
            except c3pack.PackError as e:
                sys.stderr.write(f'verify: {e}\n')
                return 2
            print(f'  {"$C3 packed":<16} {packed_emitted:>7,} bytes packed by tools/c3pack.py from the '
                  f'module ({source:,} of its {c3pack.MODULE_SIZE:,} unpacked bytes from source, '
                  f'the rest the ROM\'s)')
        print(f'  {"total":<16} {len(emitted) + packed_emitted:>7,} bytes')
        print('The data layer (asm/data/, tools/extract_data.py), apart from the figures above:')
        print(f'  {"fill":<16} {data["fill_bytes"]:>9,} bytes written by source as fill (padding rows)')
        print(f'  {"tables":<16} {data["table_bytes"]:>9,} bytes written by source as pointer tables of labels')
        print(f'  {"extracted":<16} {data["extracted_bytes"]:>9,} bytes extracted from the ROM '
              f'(build/assets/, incbin)')
        print(f'  {"packed":<16} {data["packed_bytes"]:>9,} bytes packed by the build from extracted '
              f'assets (build/packs/, incbin)')
        print(f'  {"text":<16} {data["text_bytes"]:>9,} bytes of text (strings, their pointer tables, the '
              f'dictionary, names, credits) encoded by the build from text extracted from the ROM '
              f'(build/assets/text/ -> build/text/, incbin)')
        whole = len(emitted) + packed_emitted + sum(data.values())
        print(f'  {"whole ROM":<16} {whole:>9,} of {ROM_SIZE:,} bytes accounted for')
        if args.ranges:
            for s, e in to_ranges(emitted):
                print(f'    0x{s:06X}-0x{e - 1:06X}  ({e - s} B)')

    if len(built) != len(packed):
        print(f'MISMATCH: {c3pack.MODULE_LZ} is {len(built):,} bytes, the ROM\'s pack '
              f'{len(packed):,}', file=sys.stderr)
        return 1
    if data_problems:
        print('DATA LAYER: ' + '\n  '.join(data_problems), file=sys.stderr)
        return 1
    mismatched.sort()
    if mismatched:
        print(f'MISMATCH: {len(mismatched)} emitted byte(s) differ from the ROM:', file=sys.stderr)
        for s, e in to_ranges(mismatched)[:20]:
            print(f'  0x{s:06X}-0x{e - 1:06X}', file=sys.stderr)
        return 1
    out = sys.stderr if args.json else sys.stdout
    if isolated.run_mode() == 'strace':
        print('File check: strace (asar opened no file outside the source).', file=out)
    else:
        print('UNCHECKED: no strace file-open check ran (tools/isolated.py), so a byte read '
              'from the ROM could count as source here; CI runs the check.', file=out)
    print('VERIFIED: every source-emitted byte matches the ROM.', file=out)
    return 0


if __name__ == '__main__':
    sys.exit(main())
